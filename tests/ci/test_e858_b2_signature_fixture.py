"""Synthetic Ed25519 evidence tests. NEVER supplies an actual B2 owner GO."""
import copy
from pathlib import Path
import socket
import sys
import unittest
from unittest.mock import patch

sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'scripts/ci'))

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
from e858_b_offline import SOURCE, RELEASE, canonical
from e858_phase1 import b1_package
from e858_phase1 import b2_signature_fixture as b2
from e858_phase1 import opener_candidate, launcher_candidate, practical
from e858_phase1.private_binding import Block


class SyntheticSignedEvidence(unittest.TestCase):
    def setUp(self):
        self.private=Ed25519PrivateKey.generate()  # memory-only synthetic signer
        self.public=self.private.public_key().public_bytes(Encoding.Raw,PublicFormat.Raw)
        self.now=1800000000  # deterministic synthetic UTC, not an actual window
        self.binding=dict(source_sha=SOURCE,release_ref=RELEASE,
            tooling_sha='a'*40,bundle_sha256='b'*64,sql_sha256='c'*64,
            reference_sha256='d'*64,binding_sha256='e'*64,runtime_sha256='f'*64,
            target_ca_sha256='1'*64,scope='phase1',engine='8.4',attempt_id='2'*32)

    def sign(self,changes=None,steps=b2.STEPS,signer=None):
        # The issue's real approval metadata cannot be generated by this fixture.
        records=[]
        for step in steps:
            claim=dict(kind=b2.KIND,step=step,binding=copy.deepcopy(self.binding),
                issued_at=self.now-60,expires_at=self.now+60,
                issuer=b2.ISSUER,operator=b2.OPERATOR)
            if changes:
                for key,value in changes.items():claim[key]=value
            raw=canonical(claim)
            records.append((raw,(signer or self.private).sign(raw)))
        return records

    def verify(self,records,**kwargs):
        return b2.verify_synthetic_claims(records,
            kwargs.get('expected_binding',self.binding),
            kwargs.get('public_key',self.public),kwargs.get('now',self.now))

    def test_eight_individually_signed_steps_are_only_byte_consistency_not_go(self):
        result=self.verify(self.sign())
        self.assertEqual(result['verified_steps'],8)
        self.assertEqual(result['result'],'SYNTHETIC_SIGNED_BYTES_CONSISTENT_NOT_AUTHENTICATED')
        for field in ('independent_owner_authority_verified','operator_authentication_verified',
                      'durable_one_shot_verified','execution_allowed','real_aiven_connected','production_go'):
            self.assertIs(result[field],False)
        with self.assertRaises(Block):b2.authorize(self.sign(),self.public)
        # Rechecking identical records is still possible: it proves nothing
        # about atomic consumption/replay resistance.
        self.assertEqual(self.verify(self.sign()),result)

    def test_missing_duplicate_reordered_step_or_extra_step_blocks(self):
        normal=self.sign()
        for case in (normal[:-1],normal+normal[:1],normal[::-1],
                     [normal[0]]+normal[:7],[],tuple()):
            with self.subTest(n=len(case)):
                with self.assertRaises(Block):self.verify(case)

    def test_tamper_wrong_key_or_invalid_signature_blocks(self):
        normal=self.sign()
        wrong=Ed25519PrivateKey.generate()
        tamper=list(normal);tamper[1]=(tamper[1][0]+b' ',tamper[1][1])
        for case in (tamper,normal[:1]+[(normal[1][0],b'X'*64)]+normal[2:]):
            with self.assertRaises(Block):self.verify(case)
        with self.assertRaises(Block):
            self.verify(self.sign(),public_key=wrong.public_key().public_bytes(Encoding.Raw,PublicFormat.Raw))
        with self.assertRaises(Block):self.verify(self.sign(signer=wrong))
        # Re-signing with a different key doesn't create an adopted owner trust root.
        forged=self.sign(signer=wrong)
        result=self.verify(forged,public_key=wrong.public_key().public_bytes(Encoding.Raw,PublicFormat.Raw))
        self.assertFalse(result['independent_owner_authority_verified'])
        self.assertFalse(result['execution_allowed'])

    def test_even_resigned_owner_go_or_unexpected_claims_reject(self):
        for changed in (
            dict(issuer='SIGNED_REAL_OWNER'),
            dict(operator='ACTUAL_PERSON_CONFIRMED'),
            dict(kind='E858_B2_APPROVED_V1'),
            dict(b2_go=True),
            dict(execution_allowed=True),
            dict(step='B2'),
        ):
            with self.subTest(change=next(iter(changed))):
                with self.assertRaises(Block):self.verify(self.sign(changed))

    def test_time_window_and_noninteger_injection_block(self):
        for changed in (
            dict(issued_at=self.now+1),dict(expires_at=self.now),
            dict(issued_at=self.now-2000,expires_at=self.now+60),
            dict(issued_at=True),dict(expires_at='not-a-time'),
        ):
            with self.subTest(change=str(changed)):
                with self.assertRaises(Block):self.verify(self.sign(changed))
        for now in (self.now-120,self.now+120,float('nan'),None,True):
            with self.subTest(now=str(now)):
                with self.assertRaises(Block):self.verify(self.sign(),now=now)

    def test_any_change_to_target_tooling_sql_reference_or_scope_blocks(self):
        mutations=dict(
            source_sha='0'*40,release_ref='moving-main',tooling_sha='0'*40,
            bundle_sha256='0'*64,sql_sha256='0'*64,reference_sha256='0'*64,
            binding_sha256='0'*64,runtime_sha256='0'*64,
            target_ca_sha256='0'*64,engine='9.0',scope='full17',attempt_id='0'*32
        )
        normal=self.sign()
        for field,new_value in mutations.items():
            with self.subTest(field=field):
                expected=dict(self.binding,**{field:new_value})
                with self.assertRaises(Block):self.verify(normal,expected_binding=expected)
                modified=dict(self.binding,**{field:new_value})
                with self.assertRaises(Block):self.verify(self.sign({'binding':modified}))
        with self.assertRaises(Block):self.verify(normal,expected_binding={'source_sha':SOURCE})

    def test_public_b1_and_live_methods_remain_unconditionally_closed(self):
        self.assertNotIn('scripts/ci/e858_phase1/b2_signature_fixture.py',b1_package.FILES)
        self.assertNotIn('scripts/ci/e858_phase1/owned_activation_fixture.py',b1_package.FILES)
        self.assertNotIn('scripts/ci/e858_phase1/tls_handoff_candidate.py',b1_package.FILES)
        with patch('socket.getaddrinfo') as dns,patch('socket.socket') as sock:
            self.assertEqual(self.verify(self.sign())['verified_steps'],8)
            with self.assertRaises(Block):b2.authorize({'approved':True})
            with self.assertRaises(Block):object.__new__(opener_candidate.OpenerCandidate).open()
            with self.assertRaises(Block):object.__new__(launcher_candidate.LauncherCandidate).run()
            with self.assertRaises(Block):object.__new__(practical.Adapter).prepare()
            with self.assertRaises(Block):object.__new__(practical.PrivateWire).connect()
            dns.assert_not_called();sock.assert_not_called()


if __name__=='__main__':unittest.main()
