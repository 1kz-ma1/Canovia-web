-- Owner-operated SELECT ONLY. No users, sessions, Plan or learning data rows.
-- Raw metadata stays private; feed it to integrated_release20_audit.py.
-- REFERENCES visibility is not proof of TRIGGER visibility or DDL privileges.
SELECT 'engine', CASE WHEN VERSION() LIKE '8.0.%' THEN '8.0'
 WHEN VERSION() LIKE '8.4.%' THEN '8.4' ELSE 'UNSUPPORTED' END;

SELECT 'table', TABLE_NAME, TABLE_TYPE, COALESCE(ENGINE,''), COALESCE(TABLE_COLLATION,'')
FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME;

SELECT 'column', TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME, COLUMN_TYPE,
 IS_NULLABLE, COALESCE(HEX(COLUMN_DEFAULT),'NULL'), EXTRA, COALESCE(COLLATION_NAME,'')
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
ORDER BY TABLE_NAME, ORDINAL_POSITION;

SELECT 'index', TABLE_NAME, INDEX_NAME, NON_UNIQUE, SEQ_IN_INDEX,
 COALESCE(COLUMN_NAME,''), COALESCE(SUB_PART,0), INDEX_TYPE, IS_VISIBLE,
 COALESCE(HEX(EXPRESSION),'')
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE()
ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX;

SELECT 'foreign_key', k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION,
 k.COLUMN_NAME, k.REFERENCED_TABLE_NAME, k.REFERENCED_COLUMN_NAME,
 r.UPDATE_RULE, r.DELETE_RULE,
 CASE WHEN k.REFERENCED_TABLE_SCHEMA=DATABASE() THEN 'LOCAL' ELSE 'FOREIGN' END
FROM information_schema.KEY_COLUMN_USAGE k
JOIN information_schema.REFERENTIAL_CONSTRAINTS r
 ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.TABLE_NAME=k.TABLE_NAME
 AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME
WHERE k.TABLE_SCHEMA=DATABASE() AND k.REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION;

SELECT 'check', t.TABLE_NAME, t.CONSTRAINT_NAME, HEX(c.CHECK_CLAUSE), t.ENFORCED
FROM information_schema.TABLE_CONSTRAINTS t
JOIN information_schema.CHECK_CONSTRAINTS c
 ON c.CONSTRAINT_SCHEMA=t.CONSTRAINT_SCHEMA AND c.CONSTRAINT_NAME=t.CONSTRAINT_NAME
WHERE t.TABLE_SCHEMA=DATABASE() AND t.CONSTRAINT_TYPE='CHECK'
ORDER BY t.TABLE_NAME, t.CONSTRAINT_NAME;

SELECT 'trigger', EVENT_OBJECT_TABLE, TRIGGER_NAME, EVENT_MANIPULATION,
 ACTION_TIMING, ACTION_ORDER, HEX(ACTION_STATEMENT)
FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE()
ORDER BY EVENT_OBJECT_TABLE, TRIGGER_NAME;
