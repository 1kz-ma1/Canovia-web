-- Diagnostic supplement ONLY. Append to the unchanged original metadata SQL.
-- Raw rows stay private. These SELECTs require no additional privileges.
SELECT 'semantic_version', '1';

SELECT 'semantic_index', TABLE_NAME, INDEX_NAME, NON_UNIQUE, SEQ_IN_INDEX,
 COALESCE(COLUMN_NAME,''), COALESCE(SUB_PART,0), INDEX_TYPE, IS_VISIBLE,
 COALESCE(HEX(EXPRESSION),''), COALESCE(COLLATION,''), COALESCE(NULLABLE,'')
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE()
ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX;

SELECT 'semantic_foreign_key', k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION,
 k.COLUMN_NAME, k.REFERENCED_TABLE_NAME, k.REFERENCED_COLUMN_NAME,
 r.UPDATE_RULE, r.DELETE_RULE,
 CASE WHEN k.REFERENCED_TABLE_SCHEMA=DATABASE() THEN 'LOCAL' ELSE 'FOREIGN' END,
 r.MATCH_OPTION, COALESCE(k.POSITION_IN_UNIQUE_CONSTRAINT,0)
FROM information_schema.KEY_COLUMN_USAGE k
JOIN information_schema.REFERENTIAL_CONSTRAINTS r
 ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.TABLE_NAME=k.TABLE_NAME
 AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME
WHERE k.TABLE_SCHEMA=DATABASE() AND k.REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION;
