require dirname(__DIR__, 2).'/app/Services/PrelaunchInterestScoringService.php';
$bank = require dirname(__DIR__, 2).'/config/prelaunch_interest_diagnostic.php';
$roadmap = require dirname(__DIR__, 2).'/config/canovia_public_roadmap.php';
$future = [];
foreach ($roadmap['items'] as $item) {
    if (($item['is_published'] ?? false) !== true) continue;
    if (! in_array($item['status'], ['planned', 'in_development', 'ready'], true)) {
        throw new RuntimeException('UNREVIEWED_STATIC_ROADMAP_STATUS');
    }
    $future[] = array_intersect_key($item, array_flip(['key','title','description','area','status','updated_on']));
}
$encode = fn ($value) => json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
if (($argv[1] ?? '') === '--data') {
    echo "// Generated by the pure PHP build input. Do not edit by hand.\n";
    echo "const freeze=v=>{if(v&&typeof v==='object'){Object.values(v).forEach(freeze);Object.freeze(v);}return v;};\n";
    echo 'export const bank=freeze('.$encode($bank).");\nexport const future=freeze(".$encode($future).");\n";
} elseif (($argv[1] ?? '') === '--vectors') {
    $ids = array_keys($bank['items']);
    $cases = [[], array_fill_keys($ids, 'unknown'), array_fill_keys($ids, 0), array_fill_keys($ids, 3), array_fill_keys($ids, 1)];
    foreach (array_keys($bank['categories']) as $category) {
        $primary = array_keys(array_filter($bank['items'], fn ($i) => $i['primary'] === $category && ! isset($i['secondary'])));
        foreach ([[], [0], [3], [0,3], [1,2], [3,3,3], ['unknown',3,2], [0,0,0]] as $values) {
            $answers = []; foreach ($values as $i=>$value) $answers[$primary[$i]] = $value;
            $cases[] = $answers;
        }
    }
    for ($seed=0; $seed<64; $seed++) {
        $answers = [];
        foreach ($ids as $i=>$id) {
            $v = ($i*17 + $seed*7 + intdiv($i+$seed, 3)) % 6;
            if ($v !== 5) $answers[$id] = $v === 4 ? 'unknown' : $v;
        }
        $cases[] = $answers;
    }
    $scorer = new App\Services\PrelaunchInterestScoringService;
    echo $encode(array_map(fn ($a) => ['answers'=>(object)$a, 'expected'=>$scorer->calculate($a, $bank)], $cases));
} else { throw new RuntimeException('BUILD_MODE_REQUIRED'); }
