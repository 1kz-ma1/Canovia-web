SELECT /*+ MAX_EXECUTION_TIME(5000) */ 'check', t.TABLE_NAME, t.CONSTRAINT_NAME, HEX(c.CHECK_CLAUSE), t.ENFORCED
FROM information_schema.TABLE_CONSTRAINTS t
JOIN information_schema.CHECK_CONSTRAINTS c
 ON c.CONSTRAINT_SCHEMA=t.CONSTRAINT_SCHEMA AND c.CONSTRAINT_NAME=t.CONSTRAINT_NAME
WHERE t.TABLE_SCHEMA=DATABASE() AND t.CONSTRAINT_TYPE='CHECK'
ORDER BY t.TABLE_NAME, t.CONSTRAINT_NAME LIMIT 513;
